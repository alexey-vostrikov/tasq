-- v10: сторож обхода берёт предел из одного числа, и объём обхода назван вслух.
--
-- ЧТО ИЗМЕРЕНО. Сторож из v8 ограничил ШАГИ обхода, но не объём: шаг — не строка. Обход
-- порождает пары (предок, потомок), и их число равно сумме размеров поддеревьев, то есть растёт
-- с ветвлением. Замер на законном дереве без единого цикла (глубина 9, ветвление 4):
-- 87 381 узел → 757 305 пар, граница «узлы × (предел + 1)» не нарушена.
--
-- ЧЕГО НЕ ДАЁТ СМЕНА НАПРАВЛЕНИЯ. Обход вверх (для каждого узла — цепочка предков) и обход вниз
-- (для каждого предка — его потомки) перечисляют ОДНО И ТО ЖЕ множество пар: измерено на той же
-- фикстуре — 757 305 и 757 305. Направление меняет порядок работы, но не объём; заявлять, что
-- «вверх ограничивает объём», было бы неправдой. Поэтому семантика представления не меняется,
-- меняется только предел: 16 вместо 64.
--
-- ПОЧЕМУ 16. Правило дерева — `node::MAX_DEPTH` = 16. В v8 здесь стояло 64 с оговоркой «столько
-- допускала схема до ужесточения предела»: два числа на одно правило, и расхождение не видно ни
-- из кода, ни из документации. Базы глубже 16 после v4 не создаются, а оставшиеся от старых схем
-- называет `doctor` строкой `deep:` — уменьшать предел молча нельзя, но и обходить дальше правила
-- незачем.
--
-- ЧТО ЗАЩИЩАЕТ ОТ НЕХВАТКИ МЕСТА. Сам по себе предел шагов не спасает: при 2 млн узлов и глубине
-- 16 пар может быть 34 млн — это гигабайты временного файла. Поэтому объём проверяется ДО
-- тяжёлого чтения (`tree::check_scan_budget`): верхняя граница «узлы × (предел + 1)» сравнивается
-- с пределом строк, и при превышении запрос отказывает доменной ошибкой `TRAVERSAL_BUDGET` с
-- числами вместо того, чтобы молча занять диск. Отказ виден и объясним, а испорченная база
-- (кольцо) замыкается по построению: у узла не больше одного родителя, а шаг ограничен.
--
-- Заглушку `__MAX_DEPTH__` подставляет db.rs: число берётся из `node::MAX_DEPTH`.

DROP VIEW v_node_progress;

CREATE VIEW v_node_progress AS
WITH RECURSIVE tree(ancestor_id, node_id, steps) AS (
  SELECT id, id, 0 FROM nodes
  UNION ALL
  SELECT t.ancestor_id, n.id, t.steps + 1
  FROM tree t
  JOIN nodes n ON n.parent_id = t.node_id
  -- Сторож завершаемости и предел глубины — одно число.
  WHERE t.steps < __MAX_DEPTH__
)
SELECT
  t.ancestor_id                                                       AS node_id,
  COUNT(*)                                                            AS total_count,
  SUM(CASE WHEN n.status = 'done' THEN 1 ELSE 0 END)                  AS done_count,
  SUM(n.weight)                                                       AS total_weight,
  SUM(CASE WHEN n.status = 'done' THEN n.weight ELSE 0 END)           AS done_weight
FROM tree t
JOIN nodes n ON n.id = t.node_id AND n.deleted_at IS NULL
GROUP BY t.ancestor_id;
