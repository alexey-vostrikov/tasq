-- tasq schema v9: адрес узла уникален по структуре, а не только по строке
--
-- Сейчас уникальность адреса держится `UNIQUE(project_id, path)`: две строки не могут совпасть,
-- но КОРРЕКТНОСТЬ строки ничем не гарантирована — путь можно испортить руками или чужой версией
-- бинаря, и тогда два РАЗНЫХ узла получат один адрес, потому что `seq` у них одинаковый.
--
-- Это индекс по структуре: у одного родителя внутри проекта номера детей уникальны. Из него
-- следует уникальность адреса сама собой — адрес и есть цепочка `seq` от корня.
--
-- `COALESCE(parent_id, 0)`, а не просто `parent_id`: SQLite считает NULL-ы РАЗНЫМИ значениями в
-- уникальном индексе, поэтому `UNIQUE(project_id, parent_id, seq)` не мешает двум корням иметь
-- `seq = 1`. Ноль безопасен: `id` начинается с единицы (AUTOINCREMENT).
--
-- Индекс по выражению всё же используется планировщиком для поиска детей, поэтому отдельный
-- `idx_nodes_parent(parent_id, sort_order)` остаётся: он упорядочен для листинга, этот — для
-- уникальности.

CREATE UNIQUE INDEX uq_nodes_sibling_seq
  ON nodes(project_id, COALESCE(parent_id, 0), seq);
