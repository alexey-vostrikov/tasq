//! Ветка из git: единственное значение, которое CLI берёт не из базы.
//!
//! Зачем отдельный модуль. «Текущая ветка» — это не настройка, а факт окружения, и получить
//! его можно только запуском `git`. Скрытый вызов git из середины `node::list` сделал бы
//! библиотечную функцию зависящей от рабочего каталога процесса — то есть тест, запущенный в
//! репозитории, вёл бы себя иначе, чем тот же тест вне его. Здесь вызов один, явный и только
//! там, где спрашивают ветку.
//!
//! Правило «нет значения — нет фильтра»: вне репозитория функция возвращает `None`, и
//! вызывающий не подменяет это ни `main`, ни пустой строкой. Фолбэк на `main` показал бы
//! узлы не той ветви — худший из возможных ответов на вопрос «что делать в этой ветке».

use std::process::Command;

/// Имя текущей ветки, если процесс запущен внутри репозитория git.
///
/// Отсоединённый HEAD (`detached`) и отсутствие git дают `None`: в обоих случаях «текущей
/// ветки» не существует, и придумывать её имя значило бы врать фильтру.
pub fn current_branch() -> Option<String> {
    // `symbolic-ref`, а не `rev-parse --abbrev-ref`: в свежем репозитории без единого коммита
    // HEAD ещё не указывает на ревизию, и `rev-parse` честно падает — а ветка при этом есть.
    // Отсоединённый HEAD `symbolic-ref` тоже отвергает, и это ровно тот случай, когда
    // «текущей ветки» не существует.
    let output = Command::new("git")
        .args(["symbolic-ref", "--short", "-q", "HEAD"])
        // Ошибки git не печатаются: вопрос «есть ли ветка» задают из скриптов и из TUI, и
        // поток ошибок в этом месте был бы шумом, а не сообщением.
        .stderr(std::process::Stdio::null())
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let name = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if name.is_empty() || name == "HEAD" {
        return None;
    }
    Some(name)
}

/// Разбор аргумента `--branch` в его трёх состояниях.
///
/// `None` — флага не было: фильтр не включается и поле не меняется. `Some(None)` — флаг
/// без значения: «взять у git». `Some(Some(name))` — имя как есть.
///
/// Три состояния, а не два, потому что «не упоминать ветку» и «поставить ветку, которую
/// знает git» — разные намерения, и склеивать их пустой строкой значило бы записывать в базу
/// поле, неотличимое от честно пустого. Отдельная функция, а не разбор в каждом обработчике:
/// иначе `set`, `ls` и `next` разошлись бы в трактовке — ровно там, где человек ждёт одинаковости.
pub fn resolve(value: Option<&Option<String>>) -> Option<String> {
    match value {
        None => None,
        Some(None) => current_branch(),
        Some(Some(name)) => Some(name.clone()),
    }
}
