/// Операция по имени инструмента.
pub fn operation(tool: &str) -> Option<&'static Operation> {
    OPERATIONS.iter().find(|op| op.tool == tool)
}

/// Операция, которая делает то же, что команда CLI (по её пути).
pub fn by_cli(path: &str) -> Option<&'static Operation> {
    OPERATIONS
        .iter()
        .find(|op| op.cli.is_some_and(|cli| cli == path))
}

