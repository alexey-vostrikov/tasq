//! Единое объявление операций MCP — и единственное место, где описана их поверхность.
//!
//! Зачем это здесь. Каталог инструментов был описан руками в `mcp/tools.rs` (схемы аргументов,
//! 621 строка) и отдельно в документации, а команды CLI — третьим описанием, в `main.rs`. Три
//! копии одного контракта расходятся: `tags` и `metadata` появились в CLI раньше, чем в MCP, и
//! разошлись на сутки. Теперь схема на проводе, `docs/mcp-tools.md` и бюджет токенов строятся из
//! этой таблицы, а сторож в `src/surface_checks.rs` сверяет её с деревом команд CLI.
//!
//! Чего здесь нет и почему. Команда CLI описывается в `main.rs` и остаётся там: clap строит разбор
//! аргументов на этапе компиляции, и «сгенерировать clap из таблицы» означало бы переписать все
//! команды на builder ради того же результата. Вместо этого между ними стоит сторож, и он
//! двусторонний: каждая команда CLI обязана быть названа в `cli` у какой-то операции либо в
//! `CLI_ONLY` с причиной, а каждый флаг команды — объявлен аргументом либо в `cli_only` операции.
//! Новый флаг или новая команда без объявления краснеют — это и есть то, что не работало.

/// Как аргумент инструмента называется в командной строке.
#[derive(Debug, Clone, Copy)]
pub enum CliName {
    /// Имя совпадает (`limit` ↔ `--limit`).
    Same,
    /// В CLI флаг называется иначе: у агента аргумент называет смысл, у человека флаг — действие.
    Renamed(&'static str),
    /// Аналога в CLI нет; причина — в `Operation::args_mcp_only` либо в `cli_only` команды.
    None,
}

/// Тип аргумента в схеме MCP. Ровно те, что встречаются в каталоге: строка, целое, число,
/// флаг, список строк, свободный объект и перечисление.
#[derive(Debug, Clone, Copy)]
pub enum Kind {
    Str,
    Int,
    Number,
    Bool,
    StrList,
    Object,
    /// Замкнутый набор значений; в схеме едет как `enum`.
    Choice(&'static [&'static str]),
}

impl Kind {
    /// Имя типа JSON Schema.
    pub fn json_type(self) -> &'static str {
        match self {
            Kind::Str | Kind::Choice(_) => "string",
            Kind::Int => "integer",
            Kind::Number => "number",
            Kind::Bool => "boolean",
            Kind::StrList => "array",
            Kind::Object => "object",
        }
    }
}

/// Один аргумент вызова.
#[derive(Debug, Clone, Copy)]
pub struct Arg {
    pub name: &'static str,
    pub kind: Kind,
    pub required: bool,
    pub description: &'static str,
    pub cli: CliName,
}

/// Операция: инструмент MCP и (если есть) команда CLI, которая делает то же самое.
#[derive(Debug, Clone, Copy)]
pub struct Operation {
    /// Имя инструмента в `tools/list`.
    pub tool: &'static str,
    /// Описание для модели: что делает и когда этим пользоваться.
    pub summary: &'static str,
    pub args: &'static [Arg],
    /// Возможности CLI, которых у агента нет, — с причиной на каждую.
    ///
    /// Список, а не флаг «эта операция неполная»: флаг скрыл бы следующую разницу, а запись
    /// с причиной отвечает на вопрос «почему у человека это есть, а у меня нет» без чтения кода.
    pub cli_only: &'static [(&'static str, &'static str)],
    /// Ничего не меняет — профиль `read-only` такой инструмент отдаёт.
    pub read_only: bool,
    /// Может удалить или переместить данные.
    pub destructive: bool,
    /// Повторный вызов с теми же аргументами даёт то же состояние.
    pub idempotent: bool,
    /// Путь команды CLI (`"add"`, `"dep add"`) или `None` — операция есть только в MCP.
    pub cli: Option<&'static str>,
}
