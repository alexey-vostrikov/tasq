//! Зарезервированные ключи свободных полей — единственное место, где они названы.
//!
//! `tags` и `metadata` решают разные задачи, и граница между ними до сих пор держалась на
//! договорённости в README. Здесь она записана так, чтобы её проверял код:
//!
//! - **Метка** (`nodes.tags`) отвечает «к чему относится»: это множество строк, по которому
//!   ОТБИРАЮТ (`ls --tag`, шаблоны, MCP-фильтр). Поэтому у неё своя колонка и точное сравнение в
//!   SQL: сложи метки в свободные поля — и отбор стал бы разбором JSON в Rust после чтения всех
//!   узлов, то есть перестал бы быть отбором.
//! - **Свободное поле** (`metadata`) отвечает «какое у него свойство» и принадлежит тому, кто его
//!   записал: чужой формат, происхождение, настройка. Код его не читает — кроме ключей,
//!   перечисленных ниже. Всё остальное tasq обязан переносить как есть и не толковать.
//!
//! Зачем реестр. Такие ключи уже дважды оказывались необъявленными: `saga_id` писался импортом и
//! никем не читался (а число вместо строки ломало чтение узла целиком), `reopen` читается при
//! выборе проекта и определяет, нужен ли `--force`. Ключ, который читает код, — это скрытая
//! колонка: у неё должен быть тип, аксессор и тест на ЧТЕНИЕ, а не только на запись.
//!
//! Новый ключ сюда попадает только вместе с аксессором и тестом; иначе он остаётся чужим полем.

/// `nodes.metadata.saga_id` — происхождение узла в системе-предшественнике (saga).
///
/// Пишется импортом, читается человеком и инструментами вокруг: обратной ссылки в логике нет
/// намеренно — после импорта узел живёт своей жизнью, и «где он был раньше» не должно влиять
/// ни на переходы, ни на отбор.
pub const NODE_SAGA_ID: &str = "saga_id";

/// `projects.metadata.reopen` — политика реоткрытия закрытых узлов (`force_required`/`allow`).
///
/// Читается при выборе проекта и едет вместе с ним, поэтому проверка перехода не ходит в базу.
/// Неизвестное значение читается как строгое: опечатка в настройке не должна ослаблять правило.
pub const PROJECT_REOPEN: &str = "reopen";

/// Ключи `nodes.metadata`, которые пишет или читает сам tasq.
pub const NODE_RESERVED: &[&str] = &[NODE_SAGA_ID];

/// Ключи `projects.metadata`, которые читает сам tasq.
pub const PROJECT_RESERVED: &[&str] = &[PROJECT_REOPEN];
